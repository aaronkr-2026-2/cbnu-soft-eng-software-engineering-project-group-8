import { useEffect, useRef, useState } from 'react';
import { Link } from 'react-router-dom';
import AuthMenu from './auth-menu.jsx';
import './homepage.css';
import './study-planner.css';

function localDate() {
  const now = new Date();
  return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
}
function dateAt(start, offset) {
  const date = new Date(`${start}T12:00:00`);
  date.setDate(date.getDate() + offset);
  return date;
}
const dayLabel = (start, offset) => dateAt(start, offset).toLocaleDateString('en-US', { weekday: 'short', month: 'short', day: 'numeric' });
const initialForm = () => ({ subject: '', goal: '', topics: '', level: 'Beginner', startDate: localDate(), minutes: [45, 45, 45, 45, 45, 30, 0] });
const sampleFocus = ['Loop fundamentals', 'While loops', 'Functions and parameters', 'Return values', 'Combine your skills', 'Review and reflect', 'Rest and recharge'];
const sampleTasks = [
  ['Review for-loop syntax and trace three examples.', 'Write a loop that totals a list of numbers.'],
  ['Practice while loops and stopping conditions.', 'Build a number-guessing loop with a maximum of five tries.'],
  ['Review function definitions and parameters.', 'Write functions to calculate an average and find a maximum.'],
  ['Compare printing a value with returning it.', 'Refactor yesterday\'s functions and check empty-input cases.'],
  ['Outline a small quiz program using functions.', 'Implement the quiz and test its scoring loop.'],
  ['Solve two loop exercises without notes.', 'List remaining questions and choose next week\'s focus.'],
  [],
];

export default function StudyPlanner() {
  const [form, setForm] = useState(initialForm);
  const [result, setResult] = useState(null);
  const [completed, setCompleted] = useState({});
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const requestRef = useRef(null);
  const resultsRef = useRef(null);
  useEffect(() => () => requestRef.current?.abort(), []);
  const update = event => setForm(previous => ({ ...previous, [event.target.name]: event.target.value }));
  const totalMinutes = form.minutes.reduce((sum, value) => sum + Number(value || 0), 0);
  const tasks = result?.plan.days.flatMap(day => day.tasks) || [];
  const done = Object.values(completed).filter(Boolean).length;
  const changed = result && JSON.stringify(form) !== JSON.stringify(result.input);

  const reveal = (plan, input, sample) => {
    setResult({ plan, input, sample });
    setCompleted({});
    requestAnimationFrame(() => resultsRef.current?.focus());
  };
  const preview = () => {
    const input = { ...initialForm(), subject: 'Python', goal: 'Build confidence with loops and functions.', topics: 'For loops, while loops, parameters and return values' };
    setForm(input);
    setError('');
    reveal({ title: 'Small steps, stronger Python skills', summary: 'A sample week balancing focused practice and review. This example is not generated by AI.', days: sampleFocus.map((focus, index) => ({ day: index + 1, focus, tasks: sampleTasks[index].map((title, i) => ({ title, minutes: index === 5 ? 15 : i === 0 ? 15 : 30 })) })) }, input, true);
  };
  const generate = async event => {
    event.preventDefault();
    if (!form.minutes.some(value => Number(value) >= 10) || form.minutes.some(value => Number(value) > 0 && Number(value) < 10)) { setError('Use 0 for rest days and 10–180 minutes for study days. Include at least one study day.'); return; }
    const input = { ...form, minutes: form.minutes.map(Number) };
    const controller = new AbortController();
    requestRef.current = controller;
    const timeout = setTimeout(() => controller.abort(), 65000);
    setBusy(true);
    setError('');
    try {
      const response = await fetch('/api/study-planner', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(input), signal: controller.signal });
      let data;
      try { data = await response.json(); } catch { throw new Error('The planner service is unavailable. Please try again later.'); }
      if (!response.ok) throw new Error(data.message || 'Could not create your plan. Please try again.');
      if (!data.plan || !Array.isArray(data.plan.days) || data.plan.days.length !== 7 || !data.plan.days.every(day => Array.isArray(day.tasks))) throw new Error('The planner returned an incomplete plan. Please try again.');
      reveal(data.plan, input, false);
    } catch (failure) {
      if (requestRef.current === controller) setError(controller.signal.aborted ? 'The request timed out. Please try again.' : failure instanceof TypeError ? 'Could not connect to the planner. Please try again later.' : failure.message);
    } finally {
      clearTimeout(timeout);
      if (requestRef.current === controller) { requestRef.current = null; setBusy(false); }
    }
  };
  const download = () => {
    const { plan, input, sample } = result;
    const lines = [plan.title, sample ? 'SAMPLE PLAN — not AI-generated' : 'AI-generated study plan', `${input.subject} | Starts ${input.startDate}`, plan.summary, '', ...plan.days.flatMap((day, index) => [dayLabel(input.startDate, index) + ': ' + day.focus, ...day.tasks.map((task, i) => `${completed[`${index}-${i}`] ? '[x]' : '[ ]'} ${task.title} (${task.minutes} min)`), ...(day.tasks.length ? [] : ['Rest day']), ''])];
    const url = URL.createObjectURL(new Blob([lines.join('\n')], { type: 'text/plain;charset=utf-8' }));
    const link = document.createElement('a');
    link.href = url; link.download = `study-plan-${input.startDate}.txt`; link.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  };

  return <div className="homepage planner-page">
    <header className="home-header">
      <Link to="/" className="home-logo">Student<span>AI</span></Link>
      <nav className="home-nav" aria-label="Main navigation">
        <Link to="/">Home</Link><Link to="/detect">Analysis</Link>
        <Link to="/study-planner" className="active" aria-current="page">Study Planner</Link><AuthMenu />
      </nav>
    </header>
    <main className="planner-main">
      <section className="planner-hero">
        <div><span className="home-badge">YOUR WEEK, WITH PURPOSE</span><h1>Make room for<br /><span>better learning.</span></h1><p>Turn a goal into small, achievable steps. Build a seven-day study plan around the time you actually have.</p></div>
        <div className="planner-hero-note"><span className="planner-spark" aria-hidden="true">✦</span><strong>A little progress, every day.</strong><p>Learn. Practice. Reflect.<br />Leave space to recharge.</p><span className="planner-week-dots" aria-hidden="true">● ● ● ● ● ● ○</span></div>
      </section>
      <div className="planner-layout">
        <section className="planner-setup" aria-labelledby="setup-title">
          <div className="planner-section-heading"><span className="planner-number">01</span><div><h2 id="setup-title">Shape your week</h2><p>A few details to make the plan yours.</p></div></div>
          <form onSubmit={generate}>
            <fieldset disabled={busy} className="planner-fields">
              <label htmlFor="planner-subject">What are you studying?</label>
              <input id="planner-subject" name="subject" required maxLength={100} value={form.subject} onChange={update} placeholder="e.g. Python programming" />
              <label htmlFor="planner-goal">Your goal for the week</label>
              <textarea id="planner-goal" name="goal" required maxLength={600} rows={3} value={form.goal} onChange={update} placeholder="What would you like to understand or be able to do?" />
              <label htmlFor="planner-topics">Topics to focus on <span>(optional)</span></label>
              <textarea id="planner-topics" name="topics" maxLength={600} rows={2} value={form.topics} onChange={update} placeholder="e.g. Loops, functions, debugging" />
              <div className="planner-input-row"><div><label htmlFor="planner-level">Current level</label><select id="planner-level" name="level" value={form.level} onChange={update}>{['Beginner', 'Intermediate', 'Advanced'].map(level => <option key={level}>{level}</option>)}</select></div><div><label htmlFor="planner-start">Start date</label><input id="planner-start" type="date" name="startDate" required min={localDate()} value={form.startDate} onChange={update} /></div></div>
              <div className="planner-availability-title"><h3>Time you can give</h3><span>{totalMinutes} min / week</span></div>
              <p id="time-help" className="planner-hint">Choose 10–180 minutes, or 0 for a rest day.</p>
              <div className="planner-availability">{form.minutes.map((minutes, index) => <label key={index} htmlFor={`planner-day-${index}`}><span>{form.startDate ? dayLabel(form.startDate, index) : `Day ${index + 1}`}</span><input id={`planner-day-${index}`} type="number" required min={0} max={180} step={1} aria-describedby="time-help" value={minutes} onChange={event => { const value = event.target.value; setForm(previous => ({ ...previous, minutes: previous.minutes.map((n, i) => i === index ? value === '' ? '' : Number(value) : n) })); }} /><span>min</span></label>)}</div>
              <button className="planner-generate" type="submit">{busy ? 'Creating your plan…' : result && !result.sample ? 'Create a new plan →' : 'Create my study plan →'}</button>
              <button className="planner-preview" type="button" onClick={preview}>Preview a sample plan</button>
            </fieldset>
            <div aria-live="polite">{busy && <p className="planner-hint" role="status">Finding a balance of learning, practice and rest. This may take up to a minute.</p>}{error && <p className="planner-error" role="alert">{error}</p>}</div>
            <p className="planner-privacy">Your study preferences are sent to OpenAI to create a plan. Plans are suggestions, not a guarantee of grades.</p>
          </form>
        </section>
        <section className="planner-results" aria-labelledby="plan-title" aria-busy={busy}>
          <div className="planner-section-heading"><span className="planner-number">02</span><div><h2 id="plan-title" ref={resultsRef} tabIndex={-1}>Your learning roadmap</h2><p>Seven days. One step at a time.</p></div></div>
          {!result ? <div className="planner-empty"><span aria-hidden="true">▤</span><h3>A fresh week starts here.</h3><p>Tell us what you want to learn and when you are free. Your daily tasks will appear here.</p><ol><li>Set a meaningful goal</li><li>Choose your available time</li><li>Follow your personal plan</li></ol><button type="button" onClick={preview} disabled={busy}>Explore a sample →</button></div> : <>
            <div className="planner-summary"><div className="planner-plan-meta"><span>{result.sample ? 'SAMPLE · NOT AI-GENERATED' : 'AI-GENERATED PLAN'}</span><button type="button" onClick={download}>Download ↓</button></div><h3>{result.plan.title}</h3><p>{result.plan.summary}</p><div className="planner-progress-label"><span>{done} of {tasks.length} tasks completed</span><strong>{tasks.length ? Math.round(done / tasks.length * 100) : 0}%</strong></div><progress value={done} max={tasks.length || 1} aria-label="Completed study tasks" /><p className="planner-hint">Progress lasts while this page is open. Download to keep a copy.</p></div>
            {changed && <p className="planner-draft-note">Your preferences have changed. Create a new plan to apply them; the plan below still uses your previous settings.</p>}
            <div className="planner-days">{result.plan.days.map((day, index) => <article className={`planner-day ${day.tasks.length ? '' : 'planner-rest'}`} key={day.day}><div className="planner-day-heading"><span className="planner-day-number">{String(day.day).padStart(2, '0')}</span><div><span className="planner-day-date">{dayLabel(result.input.startDate, index)}</span><h3>{day.focus}</h3></div><span className="planner-duration">{day.tasks.length ? `${day.tasks.reduce((sum, task) => sum + task.minutes, 0)} min` : 'Rest day'}</span></div>{day.tasks.length ? <ul>{day.tasks.map((task, i) => { const id = `${index}-${i}`; return <li key={id}><label className={completed[id] ? 'planner-task-done' : ''}><input type="checkbox" checked={Boolean(completed[id])} onChange={event => setCompleted(previous => ({ ...previous, [id]: event.target.checked }))} /><span>{task.title}</span><small>{task.minutes} min</small></label></li>; })}</ul> : <p>Take a break. Consistency includes time to recharge.</p>}</article>)}</div>
          </>}
        </section>
      </div>
    </main>
    <footer className="home-footer"><span className="footer-brand">StudentAI</span><p>Build better habits, one week at a time.</p></footer>
  </div>;
}
